OK = {"rights_basis": "own", "rights_note": "filmed by the owner", "audio_rights": "covered"}


@pytest.fixture
def cfg(tmp_path):
    return _settings(inbox_dir=str(tmp_path / "inbox"), media_root=str(tmp_path / "media"))


@pytest.fixture
def inbox(cfg):
    p = Path(cfg.inbox_dir)
    p.mkdir()
    return p


@pytest.mark.parametrize("fields, message", [
    ({"rights_basis": "unknown"}, "rights_basis must be one of"),
    ({"rights_basis": "nonsense"}, "rights_basis must be one of"),
    ({"rights_note": "  "}, "rights_note is required"),
    ({"rights_basis": "cc", "licence": "CC BY 4.0"}, "no author"),
    ({"rights_basis": "permission"}, "no author"),
    ({"rights_basis": "commentary", "author": " "}, "no author"),
    ({"rights_basis": "cc", "author": "Ann", "licence": "CC BY-NC 4.0"}, "NC/ND"),
    ({"audio_rights": "maybe"}, "audio_rights must be one of"),
])
def test_rights_refusals_leave_the_file(store, cfg, inbox, fields, message):
    f = inbox / "a.mp4"
    f.write_bytes(b"not probed: the rights are checked first")
    with pytest.raises(ValueError, match=message):
        LocalInboxProvider(store, cfg).ingest("a.mp4", **{**OK, **fields})
    assert f.exists() and store.list_sources() == []


