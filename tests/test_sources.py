def test_scan_inbox_lists_waiting_videos_only(cfg, inbox):
    assert scan_inbox(_settings(inbox_dir=str(inbox / "missing"))) == []
    for name in ("b.MOV", "a.mp4", ".partial.mp4", "notes.txt"):
        (inbox / name).write_bytes(b"x")
    (inbox / "dir.mp4").mkdir()
    assert [f["name"] for f in scan_inbox(cfg)] == ["a.mp4", "b.MOV"]


@needs_ffmpeg
def test_ingest_moves_the_file_and_stores_probe_stats(store, cfg, inbox):
    make_clip(inbox / "clip one.mp4")
    row = LocalInboxProvider(store, cfg).ingest(
        "clip one.mp4", rights_basis="cc", rights_note="found on Wikimedia",
        audio_rights="not_covered", author=" Ann ", url="https://x.org/v", licence="cc by-sa 4.0")
    assert not (inbox / "clip one.mp4").exists()
    assert row["local_path"] == f"sources/{row['id']}/clip.mp4"
    assert store.get_source(row["id"]) == row
    assert (Path(cfg.media_root) / row["local_path"]).is_file()
    assert row["provider"] == "local_inbox" and row["role"] == "clip"
    assert row["author"] == "Ann" and row["audio_rights"] == "not_covered"
    s = row["stats"]
    assert (s["width"], s["height"], s["has_audio"]) == (320, 568, True)
    assert 1.9 < s["duration_s"] < 2.2 and s["licence"] == "CC BY-SA 4.0"
    [clip] = sources.list_clips(store)
    assert clip["attribution"] == "Ann, https://x.org/v, CC BY-SA 4.0"


@needs_ffmpeg
def test_sound_question(store, cfg, inbox):
    make_clip(inbox / "loud.mp4")
    make_clip(inbox / "quiet.mp4", audio=False)
    provider = LocalInboxProvider(store, cfg)
    for audio in (None, "no_audio"):
        with pytest.raises(ValueError, match="has sound"):
            provider.ingest("loud.mp4", **{**OK, "audio_rights": audio})
    assert (inbox / "loud.mp4").exists()
    row = provider.ingest("quiet.mp4", **{**OK, "audio_rights": None})
    assert row["audio_rights"] == "no_audio" and row["stats"]["has_audio"] is False


@needs_ffmpeg
def test_too_big_too_long_or_not_a_video(store, inbox, tmp_path):
    make_clip(inbox / "c.mp4")
    (inbox / "fake.mp4").write_bytes(b"hello")
    for kw, name, message in ((dict(max_clip_mb=0.001), "c.mp4", "larger than"),
                              (dict(max_clip_seconds=1), "c.mp4", "longer than"),
                              ({}, "fake.mp4", "not a video")):
        cfg = _settings(inbox_dir=str(inbox), media_root=str(tmp_path / "m"), **kw)
        with pytest.raises(ValueError, match=message):
            LocalInboxProvider(store, cfg).ingest(name, **OK)
    assert store.list_sources() == [] and (inbox / "c.mp4").exists()


@needs_ffmpeg
def test_routes(store, cfg, inbox):
    make_clip(inbox / "c.mp4")
    store.add_source("research", role="reference")
    with TestClient(create_app(cfg, store=store), base_url=LOCAL) as tc:
        assert [f["name"] for f in tc.get("/api/sources/inbox").json()] == ["c.mp4"]
        r = tc.post("/api/sources/inbox/c.mp4", json={**OK, "rights_basis": "unknown"})
        assert r.status_code == 422 and "rights_basis" in r.json()["message"]
        assert tc.post("/api/sources/inbox/..%5Cc.mp4", json=OK).status_code == 422
        assert tc.post("/api/sources/inbox/x.mp4", json=OK).status_code == 404
        assert tc.post("/api/sources/inbox/c.mp4", json={**OK, "x": 1}).status_code == 422
        r = tc.post("/api/sources/inbox/c.mp4", json={**OK, "rights_basis": "permission",
                                                      "author": "bob"})
        assert r.status_code == 200 and r.json()["attribution"] == "Credit: bob"
        assert tc.get("/api/sources/inbox").json() == []
        assert [s["provider"] for s in tc.get("/api/sources?role=clip").json()] == ["local_inbox"]
        assert [s["provider"] for s in tc.get("/api/sources?role=reference").json()] == ["research"]
        assert tc.get("/api/sources?role=other").status_code == 422
