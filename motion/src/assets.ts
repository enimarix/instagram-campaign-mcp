export type AssetId = keyof typeof ASSETS;

/**
 * The asset with `src` ready for `<Img>`, `<Sprite>` or `<Html5Audio>`. Sheet entries carry
 * `frameWidth/frameHeight/frames`, so `<Sprite {...assetById("mascot")} />` works.
 */
export const assetById = <I extends AssetId>(id: I) => ({ ...ASSETS[id], src: staticFile(ASSETS[id].file) });
