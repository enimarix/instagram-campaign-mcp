// Asset registry: id → file in public/ with what a component needs to use it.
// Every file in public/ is listed in ASSETS_LICENSES.md (test/assets-licenses.test.ts checks
// both that and the sheet sizes below). Only runtime import is remotion, so node --test loads it.
import { staticFile } from "remotion";

export type AssetKind = "sprite" | "tiles" | "mascot" | "music" | "sfx";

type Entry = {
  /** Path under public/. */
  file: string;
  kind: AssetKind;
  /** Sheets: one frame's size in sheet pixels and the frame count (frames in one row). */
  frameWidth?: number;
  frameHeight?: number;
  frames?: number;
  licence: string;
  /** Music with an intro: where the loop starts, in seconds (a whole number of 30 fps frames). */
  loopStart_s?: number;
  /** Stand-in until the real asset arrives (note says when). */
  placeholder?: string;
};

const OWN = "own (generated by motion/scripts/make-assets.ts)";

const sheet = (name: string, kind: AssetKind, frameWidth: number, frameHeight: number, frames: number) =>
  ({ file: `sprites/${name}.svg`, kind, frameWidth, frameHeight, frames, licence: OWN }) as const;
const audio = (name: string, kind: AssetKind) => ({ file: `audio/${name}.wav`, kind, licence: OWN }) as const;

